# ─── SAR DETECTION ───────────────────────────────────────────────────────────

@router.post("/detect", response_model=DetectionResponse)
async def detect_oil_spill(
    file: Optional[UploadFile] = File(None),
    lat: float = Form(14.5204),
    lon: float = Form(76.3210),
    demo_mode: bool = Form(True)
):
    """
    POST /api/detect
    Upload a Sentinel-1 SAR GeoTIFF or trigger demo prediction.
    """
    try:
        temp_path = None
        if file and not demo_mode:
            # Save upload to temp file (Windows-safe path)
            temp_dir = Path(__file__).parent.parent.parent / "tmp"
            temp_dir.mkdir(exist_ok=True)
            temp_path = temp_dir / (file.filename or "upload.tiff")
            contents = await file.read()
            temp_path.write_bytes(contents)

        spill = _run_sar_detection(lat, lon, file_path=temp_path)

        if temp_path and temp_path.exists():
            temp_path.unlink()

        return DetectionResponse(
            success=True,
            spill=spill,
            message="SAR segmentation successfully completed.",
            processing_steps=[
                "Sentinel-1 GeoTIFF Ingestion",
                "Lee Speckle Filtering (7×7 window)",
                "Sigma-nought dB Normalization [-30 to 0 dB]",
                "U-Net Segmentation Pass (FP16 AMP)",
                "Contour Extraction & Georeferencing"
            ]
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Inference error: {str(e)}")


# ─── AIS ATTRIBUTION ─────────────────────────────────────────────────────────

@router.get("/attribution/{spill_id}", response_model=AttributionResponse)
async def get_vessel_attribution(
    spill_id: str,
    lat:       float = Query(14.5204),
    lon:       float = Query(76.3210),
    timestamp: str   = Query("2024-11-14T08:51:00Z")
):
    """
    GET /api/attribution/{spill_id}
    Runs weighted multi-factor AIS vessel attribution for a detected spill.
    """
    return _run_attribution(spill_id, lat, lon, timestamp)


# ─── ALERTS ──────────────────────────────────────────────────────────────────

@router.get("/alerts", response_model=List[Alert])
async def get_alerts():
    return ALERTS_STORE


@router.post("/alerts/ack")
async def acknowledge_alerts(req: AlertAckRequest):
    for alert in ALERTS_STORE:
        if alert.id in req.alert_ids:
            alert.acknowledged = True
    return {"success": True, "acknowledged_count": len(req.alert_ids)}


# ─── END-TO-END PIPELINE DEMO ────────────────────────────────────────────────

@router.post("/pipeline/run", response_model=PipelineResponse)
async def run_full_pipeline(req: PipelineRequest):
    """
    POST /api/pipeline/run
    Full pipeline: SAR Detect → AIS Attribute → Generate Alert
    Bug #5 fix: calls shared helper functions instead of route functions directly.
    """
    t_start       = time.time()
    lat, lon      = 14.5204, 76.3210
    spill_time_str = req.spill_timestamp or "2024-11-14T08:51:00Z"

    # Step 1: SAR detection via shared helper (not the HTTP handler)
    spill = _run_sar_detection(lat, lon, file_path=None)

    # Step 2: AIS attribution via shared helper
    attr_res = _run_attribution(spill.id, lat, lon, spill_time_str)

    # Step 3: Auto-generate alert
    if attr_res.vessels:
        top = attr_res.vessels[0]
        new_alert = Alert(
            id=f"ALT-{int(time.time())}",
            type="critical" if top.attribution_score > 80 else "high",
            title=f"Spill Attribution: {top.name}",
            message=(
                f"{top.name} ({top.flag}) identified as primary suspect "
                f"({top.attribution_score:.0f}% confidence) for {spill.id}."
            ),
            timestamp=datetime.now(timezone.utc).isoformat(),
            spill_id=spill.id,
            vessel_id=top.mmsi
        )
        ALERTS_STORE.insert(0, new_alert)

    total_time = round((time.time() - t_start) * 1000, 1)

    return PipelineResponse(
        success=True,
        spill=spill,
        attribution=attr_res,
        alerts_generated=1 if attr_res.vessels else 0,
        total_time_ms=total_time,
        message="End-to-end intelligence pipeline executed successfully."
    )
