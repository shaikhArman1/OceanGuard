# ─── SHARED LOGIC (reusable by both HTTP routes and internal pipeline calls) ──

def _run_sar_detection(lat: float, lon: float, file_path: Optional[Path] = None) -> SpillDetection:
    """Core SAR detection logic — used by both /detect endpoint and pipeline."""
    spill_data = inference_engine.predict_image(file_path, center_lat=lat, center_lon=lon)
    spill = SpillDetection(**spill_data)

    # Immediately run attribution to populate suspects list
    if correlator.indexed:
        spill_time = datetime.fromisoformat(spill.timestamp.replace("Z", "+00:00"))
        attrs = correlator.attribute(spill.center[0], spill.center[1], spill_time, spill.id)
        if attrs:
            spill.suspects = [a["mmsi"] for a in attrs[:3]]
            spill.top_vessel_confidence = attrs[0]["attribution_score"]
    return spill


def _run_attribution(spill_id: str, lat: float, lon: float, timestamp: str) -> AttributionResponse:
    """Core attribution logic — used by both /attribution endpoint and pipeline."""
    t_start = time.time()
    try:
        spill_time = datetime.fromisoformat(timestamp.replace("Z", "+00:00"))
    except ValueError:
        spill_time = datetime.now(timezone.utc)

    attributed = correlator.attribute(lat, lon, spill_time, spill_id)
    proc_time  = round((time.time() - t_start) * 1000, 2)

    return AttributionResponse(
        spill_id=spill_id,
        vessels=attributed,
        total_candidates_evaluated=len(correlator.tracks),
        processing_time_ms=proc_time
    )


